#include "../ft_printf.h"

size_t	ft_putstr(char *s)
{
	size_t	i;

	i = 0;
	if (s == NULL)
		s = "(null)";
	while (s[i] != '\0')
	{
		ft_putchar(s[i]);
		i++;
	}
	return (i);
}
